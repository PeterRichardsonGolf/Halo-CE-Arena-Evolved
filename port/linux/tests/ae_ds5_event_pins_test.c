int main(void)
{
	unsigned char effect[AE_DS5_EFFECT_SIZE];
	unsigned int row;

	for (row = 0; row < sizeof(events) / sizeof(events[0]); row++)
	{
		struct ae_ds5_rumble rumble;
		int ms = ae_ds5_event(effect, &rumble, (enum ae_ds5_weapon_kind)events[row][0], (enum ae_ds5_event)events[row][1], events[row][2]);

		if (ms != events[row][3] || rumble.left != events[row][4] || rumble.right != events[row][5] || rumble.ms != events[row][6])
		{
			printf("FAIL event row %u: kind %d event %d strength %d\n", row, events[row][0], events[row][1], events[row][2]);
			failures++;
		}
	}
	for (row = 0; row < sizeof(charges) / sizeof(charges[0]); row++)
	{
		struct ae_ds5_rumble rumble;
		int got = ae_ds5_charge_rumble((enum ae_ds5_weapon_kind)charges[row][0], (float)charges[row][1] / 100.0f, charges[row][2], &rumble);

		if (got)
			ae_ds5_rumble_scaled(&rumble, charges[row][3]);
		if (got != charges[row][4] || rumble.left != charges[row][5] || rumble.right != charges[row][6] || rumble.ms != charges[row][7])
		{
			printf("FAIL charge row %u: kind %d charge %d ticks %d strength %d\n", row, charges[row][0], charges[row][1], charges[row][2], charges[row][3]);
			failures++;
		}
	}
	/* the plain pads read the same table: ae_ds5_event_rumble is the rumble ae_ds5_event gives, for every kind, event and strength */
	for (row = 0; row < sizeof(events) / sizeof(events[0]); row++)
	{
		struct ae_ds5_rumble alone;

		ae_ds5_event_rumble(&alone, (enum ae_ds5_weapon_kind)events[row][0], (enum ae_ds5_event)events[row][1], events[row][2]);
		CHECK(alone.left == events[row][4] && alone.right == events[row][5] && alone.ms == events[row][6]);
	}
	/* a human weapon on the left motor, a Covenant one on the right; LIGHT 75 % and STRONG 175 % scale the motors */
	{
		struct ae_ds5_rumble human, covenant, light, strong;

		ae_ds5_event_rumble(&human, AE_DS5_WEAPON_HEAVY, AE_DS5_EVENT_SHOT, 100);
		ae_ds5_event_rumble(&covenant, AE_DS5_WEAPON_CHARGE, AE_DS5_EVENT_SHOT, 100);
		CHECK(human.left > 0 && human.right == 0 && covenant.right > 0 && covenant.left == 0);
		ae_ds5_event_rumble(&light, AE_DS5_WEAPON_HEAVY, AE_DS5_EVENT_SHOT, AE_DS5_STRENGTH_LIGHT);
		ae_ds5_event_rumble(&strong, AE_DS5_WEAPON_HEAVY, AE_DS5_EVENT_SHOT, AE_DS5_STRENGTH_STRONG);
		CHECK(light.left == (human.left * AE_DS5_RUMBLE_LIGHT + 50) / 100 && strong.left >= human.left && light.left <= human.left);
	}
	/* which events a tick holds */
	{
		struct ae_ds5_event_memory memory;
		struct ae_ds5_event_facts facts;
		int ending = 0;

		memset(&memory, 0, sizeof(memory));
		memset(&facts, 0, sizeof(facts));
		/* a weapon just taken up holds none; the same weapon with a round fired holds a shot, a charged one after a full charge */
		facts.last_fired = 5;
		CHECK(ae_ds5_events_step(&memory, &facts) == 0);
		facts.same_weapon = 1;
		CHECK(ae_ds5_events_step(&memory, &facts) == 0);
		facts.last_fired = 9;
		CHECK(ae_ds5_events_step(&memory, &facts) == AE_DS5_EVENTS_SHOT);
		facts.last_fired = 12;
		facts.charged_before = 1;
		CHECK(ae_ds5_events_step(&memory, &facts) == AE_DS5_EVENTS_SHOT_CHARGED);
		facts.charged_before = 0;
		/* the magazine going in while reloading, the chambering begun, the readying over */
		facts.reloading = 1;
		facts.rounds_loaded = 8;
		CHECK(ae_ds5_events_step(&memory, &facts) == AE_DS5_EVENTS_MAG_IN);
		facts.chambering = 1;
		CHECK(ae_ds5_events_step(&memory, &facts) == AE_DS5_EVENTS_CHAMBER);
		CHECK(ae_ds5_events_step(&memory, &facts) == 0);
		facts.same_weapon = 0;
		facts.readying = 1;
		CHECK(ae_ds5_events_step(&memory, &facts) == 0);
		facts.same_weapon = 1;
		facts.readying = 0;
		CHECK(ae_ds5_events_step(&memory, &facts) == AE_DS5_EVENTS_SETTLE);
		/* a grenade's throw gives its event once, as it begins to end */
		CHECK(!ae_ds5_event_grenade(&ending, 0) && ae_ds5_event_grenade(&ending, 1) && !ae_ds5_event_grenade(&ending, 1) &&
			!ae_ds5_event_grenade(&ending, 0) && ae_ds5_event_grenade(&ending, 1));
	}
	/* the named pulses: each known, each a pulse, none for a name that is none */
	{
		struct ae_ds5_rumble rumble;
		int index;

		for (index = 0; index < ae_ds5_pulse_count(); index++)
			CHECK(ae_ds5_pulse_named(ae_ds5_pulse_name(index), 100, &rumble) && rumble.ms > 0 && (rumble.left || rumble.right));
		CHECK(!ae_ds5_pulse_named("nothing", 100, &rumble) && !ae_ds5_pulse_named(NULL, 100, &rumble) && !strcmp(ae_ds5_pulse_name(ae_ds5_pulse_count()), ""));
		CHECK(ae_ds5_pulse_named("br", 100, &rumble) && rumble.left > 0 && rumble.right > 0);
		CHECK(ae_ds5_pulse_named("plasma-grenade", 100, &rumble) && rumble.right > 0 && rumble.left == 0);
	}
	if (failures)
		return 1;
	printf("ae_ds5_event_pins_test: all passed\n");
	return 0;
}
