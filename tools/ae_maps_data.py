#!/usr/bin/env python3
"""Writes port/linux/game/ae_maps_data.c: AE's map facts, port/assets/ae/maps.txt, and (0.6.0) the Workshop
collections CHANGE MAP's WORKSHOP folder opens into, port/assets/ae/workshop_collections.txt, as C data for the map
picker (ae_glue_setup_maps.c declares the names: the game setup spike's CHANGE MAP). tools/embed_assets.py is upstream's
and wired into its build scripts, so AE makes its own file, as tools/ae_font_data.py does for the font:

    python3 tools/ae_maps_data.py           # writes the file
    python3 tools/ae_maps_data.py --check   # exit 1 when the committed file differs from what it would write

The data are little-endian 32-bit words, padded with zeros, packed as tools/embed_assets.py packs its fonts (Android's
assembly rewriter garbles long byte strings). ae_maps_data_size (ae_workshop_collections_size) is the text's length
in bytes; the glue turns the words into text (a NUL after the last byte)."""

import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = [(Path("port/assets/ae/maps.txt"), "ae_maps_data"),
           (Path("port/assets/ae/workshop_collections.txt"), "ae_workshop_collections")]
OUTPUT = Path("port/linux/game/ae_maps_data.c")


def words(data: bytes) -> list:
    """data as lines of 32-bit words (padded with zeros), as tools/embed_assets.py words() writes them."""
    padded = data + b"\0" * (-len(data) % 4)
    values = struct.unpack(f"<{len(padded) // 4}I", padded)
    return ["\t" + ", ".join(f"0x{word:08x}" for word in values[start:start + 8]) + ","
            for start in range(0, len(values), 8)]


def text() -> str:
    """The file's text."""
    lines = [f"/* generated by tools/ae_maps_data.py from "
             f"{' and '.join(source.as_posix() for source, _ in SOURCES)}: do not edit */"]
    for source, name in SOURCES:
        data = (ROOT / source).read_bytes()
        lines += [
            f"const unsigned int {name}_words[] = {{",
            *words(data),
            "};",
            f"const int {name}_size = {len(data)};",
        ]
    return "\n".join(lines) + "\n"


def main() -> int:
    wanted = text()
    output = ROOT / OUTPUT
    if sys.argv[1:] == ["--check"]:
        if not output.is_file() or output.read_text() != wanted:
            print(f"{OUTPUT.as_posix()} is not current: run python3 tools/ae_maps_data.py")
            return 1
        return 0
    if sys.argv[1:]:
        print("usage: ae_maps_data.py [--check]")
        return 2
    output.write_text(wanted)
    return 0


if __name__ == "__main__":
    sys.exit(main())
