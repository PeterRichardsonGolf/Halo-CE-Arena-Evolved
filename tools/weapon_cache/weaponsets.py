#!/usr/bin/env python3
"""The built-in weapon sets (tools/weapon_cache/weaponsets/<name>.txt) as a generated C table.

  weaponsets.py gen [-o port/linux/game/ae_weaponsets.inc]   write the table
  weaponsets.py check                                         list the sets and their line counts

The order below is the sets' ids on the wire (AECW set id: casual 0, comp 1, btb 2); append only.
tools/test_weaponsets.py holds the checked-in table equal to the files.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SETS = ("casual", "comp", "btb")
DEFAULT_INC = os.path.join(REPO, "port", "linux", "game", "ae_weaponsets.inc")


def text_of(name):
    with open(os.path.join(HERE, "weaponsets", name + ".txt"), encoding="utf-8", newline="") as handle:
        return handle.read()


def c_literal(text):
    """one C string literal per line, so the table reads like the file"""
    parts = []
    if not text:
        return '\t""'
    for line in text.split("\n")[:-1] if text.endswith("\n") else text.split("\n"):
        escaped = line.replace("\\", "\\\\").replace('"', '\\"')
        parts.append('\t"%s\\n"' % escaped)
    return "\n".join(parts) if parts else '\t""'


def generate():
    lines = ["/* GENERATED by tools/weapon_cache/weaponsets.py gen from the .txt files in tools/weapon_cache/weaponsets: do not edit.",
             "tools/test_weaponsets.py holds this file equal to the files. The order is the sets' ids (casual 0, comp 1, btb 2). */",
             ""]
    for name in SETS:
        text = text_of(name)
        if "\r" in text:
            raise SystemExit("%s.txt: CR line ends" % name)
        lines.append('AE_WEAPONSET_TEXT("%s",' % name)
        lines.append(c_literal(text) + ")")
    return "\n".join(lines) + "\n"


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if not argv or argv[0] not in ("gen", "check"):
        print(__doc__)
        return 2
    if argv[0] == "check":
        for name in SETS:
            print("%s: %d lines" % (name, text_of(name).count("\n")))
        return 0
    out = DEFAULT_INC
    if len(argv) >= 3 and argv[1] == "-o":
        out = argv[2]
    with open(out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(generate())
    print("wrote", os.path.relpath(out, REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
