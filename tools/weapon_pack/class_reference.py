"""The shipped weapons as the yardstick: per weapon class (pistol, smg, rifle, shotgun, launcher, melee), the range every
SHIPPED weapon of the class measures in (pack_measure.py), written to class_reference.json for pack_done.py's checks 15,
19, 20 and 21 to hold a pack to. The ranges are measured from the packs, not typed; what is typed here is which class a
shipped weapon belongs to (CLASS_OF) and how much slack a range gets (TOLERANCE), both for the owner to change.

A weapon is shipped when tools/weapon_cache/registry.json has its row "active" with a pack of that key. A shipped weapon
with no class here stops the run: a new shipped weapon must be put in a class on purpose.

    class_reference.py <registry.json> <folder of ae_<key>.aepack> <class_reference.json>
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pack_measure

CLASSES = ("pistol", "smg", "rifle", "shotgun", "launcher", "melee")
CLASS_OF = {
    "magnum_scoped": "pistol", "sidearm": "pistol", "revolver": "pistol", "starter_pistol": "pistol",
    "smg": "smg", "smg_silenced": "smg", "needler": "smg", "smg_tactical": "smg",
    "battle_rifle": "rifle", "carbine": "rifle", "ar_silenced": "rifle", "ar_modern": "rifle", "dmr": "rifle",
    "evo_rifle": "rifle", "sniper_bolt": "rifle",
    "brute_shot": "launcher",
    "energy_sword": "melee",
}
# (smg_tactical, 0.9.4: the smg range's tight end, its spread 1.6 degrees and its model's rear and bottom; the owner
# 11-16 took its gate points 15 and 18 as the design: "ship it the way it is performance wise")
# a class with no shipped weapon is held to another class's range (and says so)
FALLBACK = {"shotgun": "rifle"}
# slack added each side of a measured range: the model unit is a hundredth of a world unit
TOLERANCE = {"rear": 3.0, "bottom": 3.0, "reach": 0.02, "tail_seconds": 0.25, "spread_degrees": 0.5,
             # one shipped weapon is not a range: its class's slack is this many times wider (and its spread is not held)
             "single_member_factor": 4.0}


def shipped_keys(registry):
    return [row["fragment_weapon_key"] for row in registry["rows"]
            if row.get("kind") == "weapon" and row.get("status") == "active" and row.get("fragment_weapon_key")]


def spread(values):
    values = [value for value in values if value is not None]
    return [min(values), max(values)] if values else None


def build(registry, folder):
    members = {name: [] for name in CLASSES}
    digests = {}
    for key in shipped_keys(registry):
        if key not in CLASS_OF:
            raise SystemExit("class_reference: shipped weapon %s has no class in CLASS_OF" % key)
        path = os.path.join(folder, "ae_%s.aepack" % key)
        image = open(path, "rb").read()
        digests[key] = hashlib.sha256(image).hexdigest()[:12]
        weapons = [weapon for weapon in pack_measure.measure(image) if weapon["key"] == key]
        members[CLASS_OF[key]].append(weapons[0])
    classes = {}
    for name in CLASSES:
        weapons = members[name]
        if not weapons:
            continue
        places = sorted({weapon["back"]["place"] for weapon in weapons if weapon["back"]})
        classes[name] = {
            "members": [weapon["key"] for weapon in weapons],
            "rear": spread([weapon["idle"]["rear"] for weapon in weapons if weapon["idle"]]),
            "bottom": spread([weapon["idle"]["bottom"] for weapon in weapons if weapon["idle"]]),
            "reach": {place: spread([weapon["back"]["reach"] for weapon in weapons if weapon["back"] and weapon["back"]["place"] == place])
                      for place in places},
            "tail_seconds": spread([weapon["sound_tail_seconds"] for weapon in weapons]),
            "spread_degrees": spread([weapon["spread_degrees"] for weapon in weapons]),
            "ttk_seconds": spread([weapon["ttk"].get("seconds") for weapon in weapons]),
        }
    return {"about": "generated by class_reference.py from the shipped weapons' packs: do not edit by hand",
            "registry_revision": registry.get("revision"), "packs": digests, "tolerance": TOLERANCE, "fallback": FALLBACK,
            "classes": classes}


def main(arguments):
    if len(arguments) != 3:
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    registry = json.load(open(arguments[0]))
    reference = build(registry, arguments[1])
    with open(arguments[2], "w") as file:
        json.dump(reference, file, indent=1, sort_keys=True)
        file.write("\n")
    for name, row in reference["classes"].items():
        print("%-8s %s: rear %s bottom %s reach %s tail %s" % (name, ",".join(row["members"]), row["rear"], row["bottom"], row["reach"], row["tail_seconds"]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
