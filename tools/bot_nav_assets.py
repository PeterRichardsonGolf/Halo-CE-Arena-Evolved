#!/usr/bin/env python3
"""Builds the bots' hand-placed nav files (port/assets/bot_nav/<file>.txt, port/linux/game/ae_bot_nav.h) into the game as
C data: port/linux/game/ae_bot_nav_data.c, committed beside its source.

    python3 tools/bot_nav_assets.py           writes it
    python3 tools/bot_nav_assets.py --check   exits 1 when it is not current

A nav file's name is its map's file name (no @source, no .map), letters, digits, _ and - only.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "port" / "assets" / "bot_nav"
OUTPUT = ROOT / "port" / "linux" / "game" / "ae_bot_nav_data.c"
NAME = re.compile(r"^[a-z0-9_-]{1,63}$")
LIMIT = 131072


def c_string(text):
    out = []
    for line in text.splitlines(keepends=True):
        escaped = line.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t").replace("\r", "")
        escaped = escaped.replace("\n", "\\n")
        out.append('\t\t"%s"' % escaped)
    return "\n".join(out) if out else '\t\t""'


def build():
    files = []
    for path in sorted(SOURCE.glob("*.txt")) if SOURCE.is_dir() else []:
        name = path.stem
        if not NAME.match(name):
            raise SystemExit("bot_nav_assets: bad file name: %s" % path.name)
        text = path.read_text(encoding="ascii")
        if len(text) > LIMIT:
            raise SystemExit("bot_nav_assets: %s is over %d bytes" % (path.name, LIMIT))
        files.append((name, text))
    parts = [
        "/* generated by tools/bot_nav_assets.py from port/assets/bot_nav: do not edit */",
        "",
        '#include "ae_bot_nav.h"',
        "",
        "struct ae_bot_nav_file const ae_bot_nav_files[] =",
        "{",
    ]
    for name, text in files:
        parts.append('\t{ "%s",\n%s },' % (name, c_string(text)))
    parts.append("\t{ 0, 0 }")
    parts.append("};")
    parts.append("long const ae_bot_nav_file_count = %d;" % len(files))
    return "\n".join(parts) + "\n"


def main(argv):
    text = build()
    if "--check" in argv:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != text:
            print("bot_nav_assets: %s is not current: run python3 tools/bot_nav_assets.py" % OUTPUT.relative_to(ROOT))
            return 1
        return 0
    OUTPUT.write_text(text)
    print("bot_nav_assets: wrote %s" % OUTPUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
