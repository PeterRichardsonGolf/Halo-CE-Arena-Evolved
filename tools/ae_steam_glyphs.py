#!/usr/bin/env python3
"""The Steam Controller's glyphs (port/assets/steam_pad, Kenney's Input Prompts, CC0, white on transparent, 64 by 64) as
the alpha bytes of port/linux/src/ae_steam_glyphs_data.c. Run with python3 -I; needs Pillow."""

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
FOLDER = ROOT / "port/assets/steam_pad"
OUT = ROOT / "port/linux/src/ae_steam_glyphs_data.c"
# the order of ae_steam_glyphs.h's AE_STEAM_GLYPH_*
NAMES = ["controller_button_l4", "controller_button_l5", "controller_button_r4", "controller_button_r5"]
SIZE = 64


def main() -> None:
    lines = ["/* Generated by tools/ae_steam_glyphs.py from port/assets/steam_pad (Kenney's Input Prompts, CC0): each",
             "glyph's alpha, 64 by 64, rows top first. */", '#include "ae_steam_glyphs.h"', ""]
    for name in NAMES:
        image = Image.open(FOLDER / f"{name}.png").convert("RGBA")
        if image.size != (SIZE, SIZE):
            raise SystemExit(f"{name}: not {SIZE}x{SIZE}")
        alpha = image.getchannel("A").tobytes()
        lines.append(f"static const unsigned char alpha_{name}[{SIZE * SIZE}] =")
        lines.append("{")
        for row in range(SIZE):
            lines.append("\t" + ",".join(str(value) for value in alpha[row * SIZE:(row + 1) * SIZE]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("const unsigned char *const ae_steam_glyph_alpha[AE_STEAM_GLYPH_COUNT] =")
    lines.append("{")
    lines.extend(f"\talpha_{name}," for name in NAMES)
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")


main()
